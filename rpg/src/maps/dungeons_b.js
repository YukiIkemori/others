// Map ids: ice_cave_1..2 (d_ice1/2), volcano_1..2 (d_vol1/2), star_tower_1..4 (d_star1..4),
// demon_castle_1..5 (d_demon1..5). Floor 1 of each has spawn 'entrance' and leads back to the
// world spawn named after it; stairs arrive at spawns 'up' (came from the floor above) / 'down'
// (came from below). Bosses stand on the map as 'mon:' NPCs; their scripts, the crest altars,
// the exit circles that open after each boss and the demon castle's sealed shortcut circles live
// in src/events/dungeons_b.js. Objects are mark chars in the rows (legend in `marks`); explicit
// lists hold only the 'entrance' alias of upper floors, the demon king's true form (same cell as
// his first form) and the inscriptions of the sealed circles. Every treasure is a visible chest
// (no hidden items; the `_h<n>` ids are the former examine-to-find spots, kept for old saves).
// Checked by tools/check_dungeons_b.js (layout, reachability per story state, boss framing, events).
