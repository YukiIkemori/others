  /** a crack in the floor: drops the party to the floor below */
  const fall = (to, name) => ({ warp: { to, spawn: name, sfx: 'escape' }, under: 'q' });
  /** a warp pad (two-way pads also carry the arrival spawn of their partner) */
  const pad = (to, name, here) => Object.assign({ warp: { to, spawn: name }, under: 'P' }, here ? { spawn: here } : {});
  const chest = (id, item, n, under) => ({ chest: n > 1 ? { id, item, n } : { id, item }, under: under || '.' });
  const gold = (id, g, under) => ({ chest: { id, gold: g }, under: under || '.' });
  /** a treasure chest that is really a monster (DESIGN §7.1 chest.troop) */
  const mimic = (id, item, mon, under) => ({ chest: { id, item, troop: { mons: [[mon, 1, 1]] } }, under: under || '.' });
  /** a boss (or escort) standing on the map, gone once `done` is set; sprite: 'mon:' id or a full key */
  const foe = (id, sprite, event, done, under) => ({ npc: { id, sprite: sprite.includes(':') ? sprite : 'mon:' + sprite, event, cond: '!' + done }, under: under || '.' });
  /** the floor around a boss: stepping here starts its event */
  const trigger = (event, done, under) => ({ event: { id: event, cond: '!' + done }, under: under || '.' });
  /** exit circle: a plain floor until `done`, then a warp pad out of the dungeon (tilePatch) */
  const exitCircle = (done) => ({ event: { id: 'db_exit_circle', cond: done }, under: '.' });
  /** sealed circle: a seal until `open`, then a pad running `event` (tilePatch); `here` = its arrival spawn */
  const sealedPad = (event, open, here) => ({ event: { id: event, cond: open }, spawn: here, under: '3' });
  /** a crest floating over its pedestal; appears after the boss, gone once taken */
  const crest = (id, event, boss, got) => ({ npc: { id, sprite: 'obj:crest_glow', event, cond: [boss, '!' + got] }, under: 'C' });
