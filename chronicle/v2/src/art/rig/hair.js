// CAST: 仮の絵の髪（design/art_proto/code/rig.js の hair から移して型を足した）。STYLE_REFERENCE R6・ART_REWORK §2.3-6:
// 後頭部の肌を見せない「髪の殻」（横と後ろと襟足をおおい、目のすぐ後ろのもみあげで終わる）を全部の型に付ける（bald を除く）。
//   R.Art.rig.hair.STYLES   型の一覧（頭の輪郭で人を見分ける: R.DB.looks[id].silhouette）
//   R.Art.rig.hair.draw(ctx)  ctx = {L, H, ha, grp, E, C, S, Pl, F, M, z0}（rig.js が渡す）
(function (R) {
  'use strict';
  const rig = (R.Art = R.Art || {}).rig = (R.Art.rig || {});
  const hair = (rig.hair = rig.hair || {});
  hair.STYLES = ['spiky', 'braid', 'long', 'bob', 'short', 'ponytail', 'wild', 'bald', 'curly', 'tail', 'crop', 'pigtails', 'bun', 'wave', 'swept'];

  hair.draw = function (c) {
    const { L, H, ha, grp, E, S, Pl, F, z0 } = c;
    const hm = L.hair, st = L.hairStyle || 'short';
    if (st === 'bald') {
      // 頭のてっぺんだけ禿げた形（横と後ろは髪の輪。後頭部の肌を見せない決まり、ART_REWORK §2.3-6）
      const gr = grp('hairring');
      Pl([[1, -5], [0.6, 5], [-2.6, 8], [-6.5, 9.4], [-10.2, 7.6], [-12.7, 2], [-12.6, -5], [-9.8, -9.6], [-5.5, -9.8], [-2, -7.5]].map((q) => H(q[0], q[1])), hm, 10.25, { g: gr, bevel: 2.6, nx: -0.15 });
      F(H(-5, -2), H(-6.5, 7.5), 0.5, gr, -1.2);
      return;
    }
    const s = (pts, w0, w1, z, sh) => S(pts.map((q) => H(q[0], q[1])), w0, w1, hm, z, { shadeOff: sh || 0 });
    const vol = st === 'wild' || st === 'curly' ? 1.12 : st === 'crop' ? 0.94 : 1;
    E(H(-1.8, -2.8)[0], H(-1.8, -2.8)[1], 12.4 * vol, 10.2 * vol, hm, 9.6, { g: grp('hairmass'), rot: ha });
    E(H(0.5, -5.2)[0], H(0.5, -5.2)[1], 11.2 * vol, 6.8 * vol, hm, 10.3, { g: grp('haircap'), rot: ha - 0.12 });
    // 髪の殻（プロトの直し: 横・後ろ・耳・襟足をおおう）
    const sh = L.shell || {}, fr = sh.front != null ? sh.front : 0.6, np = sh.nape != null ? sh.nape : (st === 'crop' ? 7.8 : 9.4), bn = sh.burn != null ? sh.burn : 5.2;
    const gsh = grp('hairshell');
    Pl([[3, -10.6], [fr - 0.4, -5], [fr, -0.5], [fr + 0.3, bn], [fr - 1.2, bn + 1.2], [-2.6, np - 1.6], [-6.5, np], [-10.2, np - 1.8], [-12.7, 2], [-12.6, -5], [-8.5, -10.6], [-2.5, -12.3]]
      .map((q) => H(q[0], q[1])), hm, 10.25, { g: gsh, bevel: 3.2, nx: -0.15 });
    F(H(-1, -9), H(-1.6, bn - 0.5), 0.55, gsh, -1.2);
    F(H(-5, -10), H(-6.5, np - 1.5), 0.6, gsh, -1.2);
    F(H(-9, -7.5), H(-10.5, np - 3.5), 0.55, gsh, -1);
    s([[-3, np - 3], [-3.6, np], [-3.2, np + 1.6]], 1.8, 0.4, 10.26, -0.3);
    s([[-7.5, np - 2.5], [-8.2, np + 0.6], [-8.8, np + 2]], 1.9, 0.4, 10.26, -0.4);
    s([[fr - 0.4, bn - 3], [fr, bn], [fr - 0.2, bn + 1.8]], 1.5, 0.35, 10.27, -0.2);
    // 前髪（ほとんどの型で共通の 3 房）
    const bangs = (k) => {
      k = k || 1;
      s([[1, -8], [6, -6], [7 * k, 0]], 2.6, 0.4, z0 + 0.3);
      s([[4, -9], [10, -6], [11, 1 * k]], 2.5, 0.4, z0 + 0.35);
      s([[-1, -8], [2, -4], [2.4, 0.5]], 2.6, 0.4, z0 + 0.32, -0.5);
    };
    const side = (len) => s([[-4, -6], [-4.5, 0], [-3, len || 5]], 2.3, 0.5, z0 + 0.2, -0.5);
    switch (st) {
      case 'spiky':
        s([[-4, -7], [-13, -8], [-18, -3]], 3.4, 0.4, 9.5);
        s([[-5, -3], [-13, 0], [-16, 6]], 3.2, 0.4, 9.52);
        s([[-5, 1], [-10, 5], [-11, 10]], 2.8, 0.4, 9.54);
        s([[-2, -9], [-7, -15], [-13, -15]], 3.2, 0.4, 10.35);
        s([[1, -10], [0, -16], [-5, -18]], 2.8, 0.4, 10.36);
        s([[4, -9], [6, -15], [3, -18]], 2.4, 0.3, 10.37);
        bangs(); s([[7, -8], [12, -5], [13, -1]], 1.8, 0.3, z0 + 0.36); side(4.5);
        break;
      case 'wild':
        s([[-6, -6], [-16, -4], [-19, 3]], 3.6, 0.6, 9.5);
        s([[-5, 0], [-14, 6], [-15, 12]], 3.2, 0.6, 9.52);
        s([[-1, -10], [-6, -17], [-12, -17]], 3.4, 0.5, 10.35);
        s([[3, -10], [5, -17], [1, -19]], 2.8, 0.4, 10.36);
        s([[2, -9], [9, -8], [13, -3]], 2.6, 0.5, z0 + 0.34);
        bangs(1.1); side(6);
        break;
      case 'braid': {
        bangs(); side(5);
        const pts = [[-9, 2], [-11, 7], [-11.5, 12], [-10.5, 17], [-9.5, 21]];
        pts.forEach((q, i) => { const cc = H(q[0], q[1]); E(cc[0], cc[1], 2.6 - i * 0.15, 2.3 - i * 0.1, hm, 9.3 + i * 0.01, { g: grp('braid' + i), rot: ha }); });
        const tip = H(-9.2, 24); E(tip[0], tip[1], 1.4, 2.2, L.trim, 9.2, { g: grp('tie') });
        break;
      }
      case 'ponytail':
        bangs(); side(4);
        E(H(-11, -4)[0], H(-11, -4)[1], 2.2, 2.2, L.trim, 10.3, { g: grp('tie') });
        s([[-11, -5], [-18, -3], [-19, 6], [-15, 14]], 3.4, 1.0, 9.4);
        break;
      case 'tail':
        bangs(0.9); side(6);
        E(H(-11, -7)[0], H(-11, -7)[1], 3.2, 2.6, hm, 10.32, { g: grp('knot'), rot: ha });
        s([[-12, -7], [-17, -9], [-20, -4], [-21, 3]], 2.6, 0.8, 9.4);
        break;
      case 'pigtails':
        bangs(); side(4);
        [[-10, 0], [-7, -8]].forEach((q, i) => {
          E(H(q[0], q[1])[0], H(q[0], q[1])[1], 1.9, 1.9, L.trim, 10.3 + i * 0.01, { g: grp('pt' + i) });
          s([[q[0], q[1]], [q[0] - 5, q[1] + 3], [q[0] - 6, q[1] + 10]], 2.8, 1.2, 9.4 + i * 0.01);
        });
        break;
      case 'bun':
        bangs(0.9); side(5);
        E(H(-9, -11)[0], H(-9, -11)[1], 4.6, 4.2, hm, 10.33, { g: grp('bun'), rot: ha });
        break;
      case 'long':
        s([[-6, -4], [-13, 6], [-12, 20]], 3.6, 1.0, 9.3);
        s([[-3, -2], [-9, 8], [-8, 20]], 3.2, 0.8, 9.32);
        s([[-9, -6], [-15, 2], [-15, 14]], 3.0, 0.6, 9.31);
        bangs(); s([[-4, -5], [-4, 4], [-3, 10]], 2.4, 0.6, z0 + 0.25, -0.4);
        break;
      case 'wave':
        s([[-6, -4], [-14, 4], [-10, 11], [-14, 18]], 3.6, 1.2, 9.3);
        s([[-3, -2], [-9, 6], [-6, 12], [-9, 18]], 3.2, 1.0, 9.32);
        bangs(); s([[-4, -5], [-5, 3], [-2, 8], [-4, 12]], 2.4, 0.8, z0 + 0.25, -0.4);
        break;
      case 'bob':
        s([[-6, -6], [-12, 0], [-11, 8]], 3.6, 1.6, 9.5);
        s([[-2, -7], [-7, 2], [-6, 9]], 3.2, 1.2, 9.52);
        s([[0, -9], [5, -7], [6, 0]], 3.0, 0.6, z0 + 0.3);
        s([[4, -9], [10, -6], [11, 0]], 2.6, 0.5, z0 + 0.35);
        s([[-2, -8], [-0.5, -3], [0, 1]], 2.6, 0.5, z0 + 0.32, -0.5);
        s([[-4, -5], [-5, 3], [-3.5, 8]], 2.8, 1.2, z0 + 0.25, -0.4);
        break;
      case 'curly':
        for (let i = 0; i < 7; i++) { const a = -2.6 + i * 0.5, q = H(-3 + Math.cos(a) * 11, -4 + Math.sin(a) * 10.5); E(q[0], q[1], 3.4, 3.2, hm, 10.34 + i * 0.001, { g: grp('curl' + i) }); }
        s([[2, -9], [8, -7], [10, -2]], 2.8, 0.8, z0 + 0.34); side(6);
        break;
      case 'swept':
        s([[3, -10], [-4, -14], [-12, -11]], 3.4, 0.8, 10.36);
        s([[5, -8], [-2, -12], [-10, -9]], 3.0, 0.6, 10.37);
        s([[-1, -8], [2, -4], [2.4, 0.5]], 2.2, 0.4, z0 + 0.32, -0.5); side(4);
        break;
      case 'crop':
        s([[1, -9], [6, -8], [8, -4]], 2.2, 0.4, z0 + 0.3);
        s([[-1, -9], [1, -6], [1.5, -3]], 2.2, 0.4, z0 + 0.32, -0.5);
        side(3);
        break;
      default:   // short
        bangs(); side(4.5);
        s([[-5, -5], [-12, -3], [-14, 2]], 2.6, 0.5, 9.5);
    }
  };
})(window.RPG);
